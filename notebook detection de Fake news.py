"""---
# 3. Preprocessing harmonisé

## 3.1 Binarisation

On regroupe les 6 labels en 2 classes :
- **Fake (0)** : `false`, `barely-true`, `pants-fire`
- **Real (1)** : `true`, `mostly-true`, `half-true`

> ⚠️ Le regroupement de `half-true` dans `real` est discutable — une déclaration
> à moitié vraie est aussi à moitié fausse. Ce choix affecte directement les performances.

## 3.2 Deux stratégies de feature engineering

Le groupe a exploré deux approches complémentaires :
- **`text_clean`** : texte brut nettoyé seul (utilisé par les modèles avancés P4)
- **`text_enrichi`** : `statement + speaker + context` concatenés (utilisé par les modèles classiques)

L'enrichissement donne plus de contexte au modèle mais mélange du texte et des métadonnées
dans un même vecteur — ce qui rend l'interprétation des features plus complexe.

"""

# Binarisation
LABEL_MAP_BIN = {
    'true':1,'mostly-true':1,'half-true':1,
    'barely-true':0,'false':0,'pants-fire':0
}
for df_ in [df_train, df_valid, df_test, df]:
    df_['label_binary'] = df_['label'].map(LABEL_MAP_BIN)
    df_.dropna(subset=['label_binary'], inplace=True)
    df_['label_binary'] = df_['label_binary'].astype(int)

# Nettoyage parti
def clean_party(p):
    if pd.isna(p): return 'none'
    p = str(p).lower().strip()
    if 'democrat' in p: return 'Democrat'
    if 'republican' in p: return 'Republican'
    if 'none' in p: return 'none'
    return 'other'

for df_ in [df_train, df_valid, df_test, df]:
    df_['party'] = df_['party'].apply(clean_party)

vc = df_train['label_binary'].value_counts()
print(f'Fake (0): {vc[0]} ({vc[0]/len(df_train)*100:.1f}%) | Real (1): {vc[1]} ({vc[1]/len(df_train)*100:.1f}%)')

# text_clean : texte brut nettoyé (pour modèles avancés)
def preprocess_text(text):
    """
    Nettoyage standard — appliqué identiquement sur LIAR et tous les datasets externes.
    On conserve les stopwords : sur 16 mots médiane, 'never', 'all' peuvent être informatifs.
    """
    if not isinstance(text, str): return ''
    text = text.lower()
    text = re.sub(r'http\S+|www\S+', '', text)
    text = re.sub(r'[^a-z\s]', '', text)
    return re.sub(r'\s+', ' ', text).strip()

for df_ in [df_train, df_valid, df_test, df]:
    df_['text_clean'] = df_['statement'].apply(preprocess_text)

# text_enrichi : statement + speaker + context (pour modèles classiques)
for df_ in [df_train, df_valid, df_test, df]:
    df_['text_enrichi'] = (
        df_['statement'].fillna('') + ' ' +
        df_['speaker'].fillna('') + ' ' +
        df_['context'].fillna('')
    )

df['statement_length'] = df['statement'].astype(str).apply(len)
print('Preprocessing OK')
