models_classiques = {
    'Logistic Regression': LogisticRegression(max_iter=500, class_weight='balanced', C=1.0, random_state=42),
    'Passive Aggressive' : PassiveAggressiveClassifier(max_iter=200, class_weight='balanced', random_state=42),
    'LinearSVC'          : LinearSVC(max_iter=500, class_weight='balanced', C=0.5, random_state=42),
    'Random Forest'      : RandomForestClassifier(n_estimators=200, class_weight='balanced', random_state=42, n_jobs=-1),
}

