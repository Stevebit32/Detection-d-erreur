# Cas 1 : prédiction correcte (vrai positif — fake bien classé)
tp = df_test_lime[(df_test_lime['label_binary'] == 1) & (df_test_lime['predicted'] == 1)]
# Cas 2 : erreur in-domain (faux négatif — fake prédit real)
fn_in = df_test_lime[(df_test_lime['label_binary'] == 1) & (df_test_lime['predicted'] == 0)]

print('Cas 1 — Vrai positif in-domain :')
