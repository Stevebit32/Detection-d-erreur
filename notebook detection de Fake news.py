"""---
# 6. Modèles classiques — TF-IDF sur texte enrichi

**Pourquoi 4 modèles classiques ?**

Comparer plusieurs algorithmes permet d'identifier le meilleur compromis
performances/interprétabilité sur ce dataset spécifique.

- **Logistic Regression** : modèle linéaire de référence, directement interprétable
  via ses coefficients — idéal pour l'analyse des features discriminantes
- **Passive Aggressive Classifier** : algorithme online conçu pour les grands volumes,
  sensible aux classes déséquilibrées
- **LinearSVC** : SVM linéaire — gère bien les espaces de grande dimension (TF-IDF sparse),
  souvent très compétitif en classification de texte
- **Random Forest** : ensemble de 200 arbres — robuste au bruit mais moins interprétable

**Texte enrichi** (`statement + speaker + context`) : le speaker et le contexte
fournissent des indices sur l'identité du locuteur sans passer par les métadonnées structurées.

"""

