# Définition de la fonction d'évaluation BERT out-of-domain
def predict_bert_dataset(model, texts, labels, tokenizer, max_len, batch_size, device):
    """
    Applique le modèle BERT fine-tuné sur un dataset externe.
    Retourne accuracy, F1-macro et les prédictions.
    """
    ds     = LiarDataset(texts, labels, tokenizer, max_len)
    loader = DataLoader(ds, batch_size=batch_size, shuffle=False, num_workers=2)

    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for batch in loader:
            ids    = batch['input_ids'].to(device)
            mask   = batch['attention_mask'].to(device)
            labs   = batch['label'].to(device)
            outputs = model(input_ids=ids, attention_mask=mask)
            all_preds.extend(outputs.logits.argmax(dim=1).cpu().numpy())
            all_labels.extend(labs.cpu().numpy())

    acc = accuracy_score(all_labels, all_preds)
    f1  = f1_score(all_labels, all_preds, average='macro')
    return acc, f1, all_preds

