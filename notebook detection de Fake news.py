for name, clf in models_classiques.items():
    pipe = Pipeline([('tfidf', TfidfVectorizer(**tfidf_params_enr)), ('clf', clf)])
    pipe.fit(X_train_enr, y_train_enr)
    y_pred = pipe.predict(X_test_enr)
    acc = accuracy_score(y_test_enr, y_pred)
    f1  = f1_score(y_test_enr, y_pred, average='macro')
    results_classiques[name] = {'Accuracy': round(acc,3), 'F1-macro': round(f1,3)}
    trained_pipes[name] = (pipe, y_pred)
    print(f'{name:25s} | Accuracy:{acc:.3f} | F1-macro:{f1:.3f}')

print('\nTous les modèles classiques entraînés.')

